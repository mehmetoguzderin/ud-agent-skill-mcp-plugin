import base64
import hashlib
import io
import json
import os
from pathlib import Path
import tempfile
import stat
import unittest
from unittest import mock

from ud_agent.snapshot_receiver import MAX_CHUNK, _manifest, receive_snapshot


def sha(value):
    return hashlib.sha256(value).hexdigest()


def manifest(entries):
    files = [{"path": path, "size": len(data), "sha256": sha(data)} for path, data in entries]
    digest = sha(json.dumps(files, ensure_ascii=False, separators=(",", ":")).encode())
    return files, digest


def frames(entries):
    files, digest = manifest(entries)
    output = [{"type": "begin", "manifest": files, "snapshot_sha256": digest}]
    for path, data in entries:
        for offset in range(0, len(data), MAX_CHUNK):
            output.append({"type": "chunk", "path": path, "offset": offset,
                           "bytes_base64": base64.b64encode(data[offset:offset + MAX_CHUNK]).decode()})
        output.append({"type": "file_end", "path": path})
    output.append({"type": "end", "snapshot_sha256": digest})
    return digest, output


def wire(records):
    return b"".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")).encode() + b"\n" for row in records)


class SnapshotReceiverTests(unittest.TestCase):
    def setUp(self):
        self.parent = tempfile.TemporaryDirectory(prefix="ud-worker-transfer-")
        os.chmod(self.parent.name, 0o700)
        self.addCleanup(self.parent.cleanup)

    def receive(self, data, digest):
        return receive_snapshot(io.BytesIO(data), digest, self.parent.name)

    def test_cross_language_javascript_manifest_digest(self):
        # This fingerprint was generated by Node's JSON.stringify and SHA-256.
        vector = [{"path": "a/é.conllu", "size": 1, "sha256": "a" * 64},
                  {"path": "字.conllu", "size": 0, "sha256": "b" * 64},
                  {"path": "😀.conllu", "size": 2, "sha256": "c" * 64}]
        self.assertEqual(_manifest(vector, "2834c95b22c548e1cdc4e64d6c38913854b10980de82c0de6cc0147edc395dd2"), vector)
        # JavaScript UTF-16 order places this surrogate pair before U+E000.
        ordering = [{"path": "😀", "size": 0, "sha256": "a" * 64},
                    {"path": "\ue000", "size": 0, "sha256": "b" * 64}]
        self.assertEqual(_manifest(ordering, "480a63eeb8e8abb1075381e0c610a64aaa1649357a8d20b7713a12fa45efccff"), ordering)
        with self.assertRaises(ValueError):
            _manifest(list(reversed(ordering)), "480a63eeb8e8abb1075381e0c610a64aaa1649357a8d20b7713a12fa45efccff")

    def test_stages_exact_multichunk_binary_and_empty_files_then_cleans(self):
        data = bytes(range(256)) * 300
        digest, rows = frames([("empty", b""), ("nested/é.conllu", data)])
        lease = self.receive(wire(rows), digest)
        path = Path(lease.path)
        self.assertEqual((path / "empty").read_bytes(), b"")
        self.assertEqual((path / "nested/é.conllu").read_bytes(), data)
        if os.name == 'nt':
            # The Windows receiver binds ordinary non-reparse identities;
            # its outer native staging authority supplies ACL privacy.
            self.assertFalse(getattr(os.lstat(path), 'st_file_attributes', 0) & 0x400)
            self.assertFalse(getattr(os.lstat(path / "nested/é.conllu"), 'st_file_attributes', 0) & 0x400)
            self.assertEqual(lease.identity, (os.stat(path).st_dev, os.stat(path).st_ino))
        else:
            self.assertEqual(os.stat(path).st_mode & 0o077, 0)
            self.assertEqual(os.stat(path / "nested/é.conllu").st_mode & 0o077, 0)
        lease.cleanup()
        lease.cleanup()
        self.assertFalse(path.exists())

    def test_framed_stdin_preserves_the_following_request_without_reading_it(self):
        digest, rows = frames([("sample.conllu", b"preserved\r\n")])
        request = b'{"operation":"validation_report","arguments":{}}\n'
        stream = io.BytesIO(wire(rows) + request)
        with receive_snapshot(stream, digest, self.parent.name, stop_at_end=True) as snapshot:
            self.assertEqual((Path(snapshot.path) / "sample.conllu").read_bytes(), b"preserved\r\n")
            self.assertEqual(stream.readline(), request)
            self.assertEqual(stream.read(), b"")

    def test_promotes_only_a_verified_snapshot_into_the_owned_volume(self):
        digest, rows = frames([("sample.conllu", b"unchanged\r\n")])
        with self.receive(wire(rows), digest) as lease:
            lease.promote("data")
        self.assertEqual((Path(self.parent.name) / "data/sample.conllu").read_bytes(), b"unchanged\r\n")
        with self.assertRaises(RuntimeError):
            lease.promote("data")

    def test_promotion_rejects_existing_or_unsupported_destination(self):
        digest, rows = frames([("sample", b"bytes")])
        (Path(self.parent.name) / "data").mkdir()
        with self.receive(wire(rows), digest) as lease:
            with self.assertRaisesRegex(RuntimeError, "CONFLICT"):
                lease.promote("data")
            with self.assertRaisesRegex(RuntimeError, "INVALID"):
                lease.promote("../outside")
        self.assertEqual(sorted(os.listdir(self.parent.name)), ["data"])

    def test_rejects_hostile_and_colliding_paths_before_creating_files(self):
        for name in ["/".join(["x"] * 65), "x" * 256, "../outside", "/absolute", "a/../../x", "a//x", "a\\x", "C:x", ".git/config", "x/.GIT/config", "CON", "a.", "a ", "a/\x00"]:
            with self.subTest(name=name):
                digest, rows = frames([(name, b"secret")])
                with self.assertRaises(ValueError):
                    self.receive(wire(rows), digest)
                self.assertEqual(os.listdir(self.parent.name), [])
        for entries in [[("x", b"a"), ("x", b"a")], [("a", b"a"), ("a/b", b"b")], [("A", b"a"), ("a", b"b")], [("é", b"a"), ("e\u0301", b"b")]]:
            digest, rows = frames(entries)
            with self.assertRaises(ValueError):
                self.receive(wire(rows), digest)
            self.assertEqual(os.listdir(self.parent.name), [])

    def test_rejects_corrupt_reordered_truncated_duplicate_and_extra_frames(self):
        digest, rows = frames([("data", b"hello")])
        variants = []
        bad = [dict(row) for row in rows]; bad[1]["bytes_base64"] = base64.b64encode(b"wrong").decode(); variants.append(wire(bad))
        bad = [dict(row) for row in rows]; bad[1]["offset"] = 1; variants.append(wire(bad))
        bad = [dict(row) for row in rows]; bad[1]["bytes_base64"] = 'a==='; variants.append(wire(bad))
        variants.extend([wire(rows[:-1]), wire(rows)[:-1], wire(rows + [rows[-1]]), wire([rows[0], rows[0]]), b'{"type":"begin","type":"begin"}\n', b'\xff\n'])
        for value in variants:
            with self.subTest(value=value[:80]):
                with self.assertRaises(ValueError):
                    self.receive(value, digest)
                self.assertEqual(os.listdir(self.parent.name), [])

    def test_expected_digest_must_be_provided_outside_frames(self):
        digest, rows = frames([("data", b"hello")])
        with self.assertRaises(ValueError):
            self.receive(wire(rows), "0" * 64)
        self.assertEqual(os.listdir(self.parent.name), [])
        with self.assertRaises(ValueError):
            self.receive(wire(rows), "invalid")

    def test_rejects_unsafe_staging_parent_and_symlink_parent(self):
        digest, rows = frames([])
        if os.name == 'nt':
            ordinary = Path(self.parent.name) / 'ordinary'
            ordinary.write_bytes(b'preserved')
            with self.assertRaises(ValueError):
                receive_snapshot(io.BytesIO(wire(rows)), digest, str(ordinary))
            self.assertEqual(ordinary.read_bytes(), b'preserved')
            ordinary.unlink()
        else:
            os.chmod(self.parent.name, 0o755)
            with self.assertRaises(ValueError):
                self.receive(wire(rows), digest)
            os.chmod(self.parent.name, 0o700)
        link = os.path.join(self.parent.name, "link")
        os.symlink(self.parent.name, link, target_is_directory=True)
        with self.assertRaises((OSError, ValueError)):
            receive_snapshot(io.BytesIO(wire(rows)), digest, link)

    def test_failure_after_first_file_cleans_already_written_files(self):
        digest, rows = frames([("a", b"first"), ("b", b"second")])
        bad = [dict(row) for row in rows]
        bad[-2]["path"] = "other"
        with self.assertRaises(ValueError):
            self.receive(wire(bad), digest)
        self.assertEqual(os.listdir(self.parent.name), [])

    def test_intermediate_symlink_cannot_redirect_staged_file(self):
        import ud_agent.snapshot_receiver as receiver
        with tempfile.TemporaryDirectory(prefix="ud-outside-") as outside:
            original = receiver._create_file
            def inject(stage_fd, path):
                if isinstance(stage_fd, str):
                    os.symlink(outside, Path(stage_fd) / 'nested', target_is_directory=True)
                else:
                    os.symlink(outside, "nested", dir_fd=stage_fd)
                return original(stage_fd, path)
            digest, rows = frames([("nested/file", b"secret")])
            with mock.patch.object(receiver, "_create_file", side_effect=inject):
                with self.assertRaises((OSError, ValueError, RuntimeError)):
                    self.receive(wire(rows), digest)
            self.assertEqual(os.listdir(outside), [])
            if os.name == 'nt':
                # Reparse cleanup is deliberately refused, retaining the exact
                # owned stage for the caller instead of traversing the link.
                stages = list(Path(self.parent.name).iterdir())
                self.assertEqual(len(stages), 1)
                self.assertTrue((stages[0] / 'nested').is_symlink())
                (stages[0] / 'nested').unlink(); stages[0].rmdir()
            self.assertEqual(os.listdir(self.parent.name), [])

    def test_cleanup_failure_is_reported_not_hidden(self):
        digest, rows = frames([("a", b"first")])
        cleanup = '_remove_windows_contents' if os.name == 'nt' else '_remove_contents'
        with mock.patch('ud_agent.snapshot_receiver.' + cleanup, side_effect=OSError('fixture failure')):
            with self.assertRaisesRegex(RuntimeError, 'CLEANUP_UNVERIFIED'):
                self.receive(wire(rows[:-1]), digest)


if __name__ == '__main__':
    unittest.main()
