import { test, expect } from 'vitest';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { sourceReceipt } from '../../scripts/release/candidate.mjs';
import { retainSourceSnapshot } from '../../scripts/release/prepare.mjs';

test('diagnostic source replay retains exact original files rather than mutable source paths', () => {
  const root = mkdtempSync(path.join(os.tmpdir(), 'ud-retained-source-'));
  try {
    const original = path.join(root, 'original'), snapshot = path.join(root, 'snapshot'); mkdirSync(path.join(original, 'packages/demo'), { recursive: true }); writeFileSync(path.join(original, 'packages/demo/main.js'), 'export const value = true;\n');
    const receipt = sourceReceipt(original); retainSourceSnapshot(original, receipt, snapshot);
    expect(sourceReceipt(snapshot).sha256).toBe(receipt.sha256);
    writeFileSync(path.join(original, 'packages/demo/main.js'), 'export const value = false;\n');
    expect(readFileSync(path.join(snapshot, 'packages/demo/main.js'), 'utf8')).toBe('export const value = true;\n');
    expect(() => retainSourceSnapshot(original, receipt, path.join(root, 'stale'))).toThrow(/exact current/);
    expect(() => retainSourceSnapshot(original, sourceReceipt(original), snapshot)).toThrow(/exact current/);
  } finally { rmSync(root, { recursive: true, force: true }); }
});

test('snapshots exclude nested generated artifacts and reject output inside copied source', () => {
  const root = mkdtempSync(path.join(os.tmpdir(), 'ud-retained-source-bounds-'));
  try {
    mkdirSync(path.join(root, 'packages/demo/.artifacts/old-candidate'), { recursive: true });
    writeFileSync(path.join(root, 'packages/demo/main.js'), 'export const value = 1;\n');
    writeFileSync(path.join(root, 'packages/demo/.artifacts/old-candidate/payload'), 'discardable generated bytes');
    const receipt = sourceReceipt(root);
    expect(receipt.files.map(row => row.path)).toEqual(['packages/demo/main.js']);
    const nested = path.join(root, 'packages/demo/new-candidate');
    expect(() => retainSourceSnapshot(root, receipt, nested)).toThrow(/outside its copied input trees/);
    expect(existsSync(nested)).toBe(false);
    const output = path.join(root, '.artifacts/new-candidate/source');
    retainSourceSnapshot(root, receipt, output);
    expect(sourceReceipt(output)).toEqual(receipt);
    expect(existsSync(path.join(output, 'packages/demo/.artifacts'))).toBe(false);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
